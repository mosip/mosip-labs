"""Testcase conventions that CoverageCli `check` does not enforce.

CoverageCli already blocks: duplicate / missing uniqueIdentifier, restMethod vs script-class verb,
orphan cases, unwired/empty YAML, unreachable endpoints. Do not re-implement those here.

This validator adds (rules configured per module in <module repo>/.crewline/qa/profile.yaml):
  NAME-001  case name starts with the module's case-name prefix
  NAME-002  uniqueIdentifier matches the module's ID pattern
  NAME-003  uniqueIdentifier subject token matches the YAML root key (style consistency)
  NAME-004  uniqueIdentifier is unique module-wide, case-insensitive (CoverageCli's rule, for branches without it)
  DEP-001   every $ID:<key>$ token resolves to a `_sid` case whose suite entry captures that field
  DEP-002   every additionalDependencies entry names an existing uniqueIdentifier

--scope changed (default when --base is given) evaluates only cases added or modified since the
base ref, so pre-existing debt is reported by --scope all but does not block new work.
"""
from __future__ import annotations

import re

from .apitestrig import Module
from .result import BLOCK, INFO, WARN, Result

ID_TOKEN = re.compile(r"\$ID:([A-Za-z0-9_.\-]+?)\$")


def sid_keys(module: Module) -> dict[str, str]:
    """Map every capturable $ID: key to the case that produces it.

    Commons script classes store IDs only for `_sid` cases (the check is at their call sites). A module's own script
    class may call writeAutoGeneratedId without that check (Verified: inji-verify SimplePostForAutoGenIdWithHeaders,
    commons 1.5.0 AdminTestUtil.writeAutoGeneratedId has no _sid gate); list such classes in
    `testcase_rules.capture_without_sid` and every case they run produces keys. A class that reads the key per case from
    an input field (Verified: pre-registration PreRegPiiRequest, `input._idKeyName`) is listed in
    `testcase_rules.id_key_from_input` as class -> field."""
    rules = module.profile.get("testcase_rules", {})
    extra = rules.get("extra_id_fields_by_class", {})
    extra_gate = rules.get("extra_id_fields_gate", {})           # class -> case-name token for its extra fields
    ungated = set(rules.get("capture_without_sid", []))
    from_input = rules.get("id_key_from_input", {})             # class -> input field naming the case's ID key
    capture, gated_extra, always, input_key = {}, {}, set(), {}
    for t in module.suite_tests():
        cls = t.script_class.rsplit(".", 1)[-1]
        capture.setdefault(t.yml, set()).update(t.id_key_names)
        if cls in extra_gate:
            gated_extra.setdefault(t.yml, []).append((extra_gate[cls].lower(), extra.get(cls, [])))
        else:
            capture[t.yml].update(extra.get(cls, []))
        if cls in ungated:
            always.add(t.yml)
        if cls in from_input:
            input_key[t.yml] = re.compile(r'"' + re.escape(from_input[cls]) + r'"\s*:\s*"([A-Za-z0-9_.]+)"')
    keys = {}
    for c in module.cases():
        stem = c.name.split("_", 1)[1] if "_" in c.name else c.name
        if "_sid" in c.name.lower() or c.yml in always:
            fields = set(capture.get(c.yml, ()))
            if c.yml in input_key:
                fields.update(input_key[c.yml].findall(str(c.fields.get("input", ""))))
            for fld in fields:
                keys[f"{stem}_{fld}"] = f"{c.yml}::{c.name}"
        for token, fields in gated_extra.get(c.yml, ()):
            if token in c.name.lower():
                for fld in fields:
                    keys[f"{stem}_{fld}"] = f"{c.yml}::{c.name}"
    return keys


def changed_case_keys(module: Module, base: str) -> set[tuple[str, str]]:
    before = {(c.yml, c.name): c.fields for c in module.base_cases(base)}
    return {(c.yml, c.name) for c in module.cases() if before.get((c.yml, c.name)) != c.fields}


def run(module: Module, scope: str = "all", base: str | None = None) -> Result:
    res = Result("testcase", inputs={"module_root": str(module.root), "scope": scope, "base": base})
    rules = module.profile.get("testcase_rules", {})
    prefix = rules.get("case_name_prefix")          # one prefix, or a list when a module has several case families
    prefixes = tuple(prefix) if isinstance(prefix, list) else ((prefix,) if prefix else ())
    uid_re = re.compile(rules["unique_identifier_pattern"]) if rules.get("unique_identifier_pattern") else None
    sev = {**{"NAME-001": BLOCK, "NAME-002": BLOCK, "NAME-003": WARN, "DEP-001": BLOCK, "DEP-002": BLOCK},
           **rules.get("severity", {})}

    cases = module.cases()
    parse_errors = dict(module.parse_errors)
    in_scope = changed_case_keys(module, base) if scope == "changed" and base else None
    changed_files = set(module.changed_paths(base)) if scope == "changed" and base else None
    for rel, msg in parse_errors.items():
        touched = changed_files is None or rel in changed_files
        res.add("YAML-PARSE", BLOCK if touched else WARN,
                f"YAML does not parse{'' if touched else ' (not touched by this change)'}: {msg}", path=rel,
                remediation="fix the file" if touched else "pre-existing upstream defect; report it, don't fix it in this task")
    keys = sid_keys(module)
    uids = {(c.uid or "").lower() for c in cases if c.uid}
    unwired = set(module.profile.get("ignore_yaml", []))
    texts: dict[str, list[str]] = {}

    uid_owners: dict[str, list[str]] = {}
    for c in cases:
        if c.uid:
            uid_owners.setdefault(c.uid.lower(), []).append(f"{c.yml}::{c.name}")
    for c in cases:
        if c.yml in unwired or (in_scope is not None and (c.yml, c.name) not in in_scope):
            continue
        at = dict(path=c.yml, line=c.line)
        # Also enforced by CoverageCli where a module has the matrix; upstream branches may not.
        if c.uid and len(uid_owners[c.uid.lower()]) > 1:
            others = [o for o in uid_owners[c.uid.lower()] if o != f"{c.yml}::{c.name}"]
            res.add("NAME-004", BLOCK, f"uniqueIdentifier '{c.uid}' also used by {', '.join(others)[:160]}", **at)
        if prefixes and not c.name.startswith(prefixes):
            res.add("NAME-001", sev["NAME-001"], f"case '{c.name}' does not start with {' or '.join(map(repr, prefixes))}",
                    remediation=f"rename to {prefixes[0]}<Subject>_<Scenario>[_Smoke][_sid]", **at)
        if c.uid and uid_re and not uid_re.match(c.uid):
            res.add("NAME-002", sev["NAME-002"], f"uniqueIdentifier '{c.uid}' does not match {uid_re.pattern}", **at)
        if c.uid and uid_re and uid_re.match(c.uid):
            subject = c.uid.split("_")[2] if c.uid.count("_") >= 3 else ""
            if subject.lower() != c.root.lower():
                res.add("NAME-003", sev["NAME-003"],
                        f"uniqueIdentifier subject '{subject}' differs from YAML root key '{c.root}'", **at)
        text = f"{c.fields.get('input', '')}\n{c.fields.get('output', '')}\n{c.fields.get('endPoint', '')}"
        for key in dict.fromkeys(ID_TOKEN.findall(text)):
            if key not in keys:
                lines = texts.setdefault(c.yml, module.read(c.yml).splitlines())
                line = next((n for n in range(c.line, len(lines) + 1) if f"$ID:{key}$" in lines[n - 1]), c.line)
                res.add("DEP-001", sev["DEP-001"], f"$ID:{key}$ is not produced by any _sid case in this module "
                        f"(used by {c.uid or c.name})",
                        path=c.yml, line=line,
                        evidence="producer key = <case name minus first '_' segment>_<idKeyName or class extra field>",
                        remediation="point to an existing _sid case, or capture the field in its suite entry")
        deps = c.fields.get("additionalDependencies") or []
        for dep in [deps] if isinstance(deps, str) else deps:
            for d in str(dep).split(","):
                if d.strip() and d.strip().lower() not in uids:
                    res.add("DEP-002", sev["DEP-002"], f"additionalDependencies '{d.strip()}' is not a known uniqueIdentifier", **at)

    res.inputs["cases_evaluated"] = len(cases) if in_scope is None else len(in_scope)
    res.inputs["sid_keys"] = len(keys)
    if in_scope is not None and not in_scope:
        res.add("SCOPE", INFO, "no added or modified cases since base")
    return res.finish()
